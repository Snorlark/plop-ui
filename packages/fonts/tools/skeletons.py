# ---------- skeleton primitives (unit space: y 0=baseline, 1=cap height) ----------
def arc(cx, cy, rx, ry, a0, a1, n=48):
    pts = []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        pts.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return pts

def quad(p0, c, p1, n=24):
    out = []
    for i in range(n + 1):
        t = i / n
        out.append(((1-t)**2*p0[0] + 2*(1-t)*t*c[0] + t*t*p1[0],
                    (1-t)**2*p0[1] + 2*(1-t)*t*c[1] + t*t*p1[1]))
    return out

